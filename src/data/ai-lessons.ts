type Slide = Record<string, unknown>;

const title = (t: string, sub: string): Slide => ({ type: "title", title: t, sub });
const why = (q: string, sub: string): Slide => ({ type: "why", q, sub });
const analogy = (t: string, left: [string, string], right: [string, string]): Slide => ({ type: "analogy", title: t, left, right });
const three = (t: string, items: [string, string, string][]): Slide => ({ type: "three", title: t, items });
const grid = (t: string, items: [string, string][]): Slide => ({ type: "grid", title: t, items });
const steps = (t: string, items: string[], note?: string): Slide => ({ type: "steps", title: t, items, note });
const table = (t: string, head: string[], rows: string[][], note?: string): Slide => ({ type: "table", title: t, head, rows, note });
const cards = (t: string, a: [string, string, string[]], b: [string, string, string[]], common?: string): Slide => ({
  type: "cards",
  title: t,
  a: { tag: a[0], head: a[1], lines: a[2] },
  b: { tag: b[0], head: b[1], lines: b[2] },
  common,
});
const chat = (t: string, turns: [string, string, number?][], legend: [string, string][]): Slide => ({ type: "mockChat", title: t, turns, legend });
const end = (q: string, next: string): Slide => ({ type: "end", q, next });

